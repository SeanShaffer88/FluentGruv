#!/usr/bin/env python3
"""Regenerate ai-bundle.md from the individual FluentGruv files.

Run after any spec edit, in the same change:
    python scripts/build-bundle.py
The bundle is a snapshot; if it ever differs from the individual
files, the individual files win.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXAMPLES = [
    "wireframe-utility",
    "wireframe-exorsyst",
    "wireframe-yttraydl",
    "wireframe-safereturn",
    "wireframe-roomforge",
]


def read(rel: str) -> str:
    return (ROOT / rel).read_text(encoding="utf-8").rstrip("\n")


def main() -> None:
    version = json.loads(read("tokens.json"))["version"]
    bundle = (
        f"# FluentGruv — AI Bundle (v{version})\n\n"
        "The complete FluentGruv spec in one file: enforcement prompt, layout "
        "specification, tokens (dark + light), the machine-readable tokens.json, "
        "and every example wireframe. Generated by `scripts/build-bundle.py` "
        f"from the individual files in this repository at v{version} — if "
        "anything differs, the individual files win.\n\n---\n\n"
        + read("AGENT_PROMPT.md")
        + "\n\n---\n\n"
        + read("SPEC.md")
        + "\n\n---\n\n"
        + read("TOKENS.md")
        + "\n\n---\n\n# tokens.json (verbatim)\n\n```json\n"
        + read("tokens.json")
        + "\n```\n"
    )
    for name in EXAMPLES:
        bundle += (
            f"\n\n---\n\n# examples/{name}.txt (verbatim)\n\n```text\n"
            + read(f"examples/{name}.txt")
            + "\n```\n"
        )
    (ROOT / "ai-bundle.md").write_text(bundle, encoding="utf-8")
    print(f"ai-bundle.md regenerated for v{version} ({len(bundle)} bytes)")


if __name__ == "__main__":
    main()
